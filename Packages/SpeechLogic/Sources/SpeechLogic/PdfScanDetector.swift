import Foundation
import PDFKit

/// One scan-detection verdict: how a document's pages look, and why.
///
/// `reason` is diagnostic text only — it lands in the device log. The
/// booleans carry the decision. A verdict is per DOCUMENT, assembled by
/// sampling; a detector never walks an entire 800-page book to make up its
/// mind.
public struct PdfScanVerdict {
    /// The sampled pages carry no text layer at all (the blank-scan shape).
    public var looksScanned: Bool
    /// A meaningful share of the sampled pages carry the same scanner
    /// watermark as their whole text layer.
    public var watermarkOnly: Bool
    /// How many pages were examined.
    public var sampledPages: Int
    /// Why the verdict came out the way it did.
    public var reason: String

    /// Either verdict sends a page to OCR.
    public var needsOCR: Bool { looksScanned || watermarkOnly }
}

/// Decides whether a PDF is a scan, tolerating the watermark-only text layer
/// that scanner apps (CamScanner and its clones) write onto every page.
///
/// A character-count floor cannot tell the two apart. CamScanner makes
/// "Scanned by CamScanner" a real, invisible, selectable text layer, which
/// clears any low "does this page have text" bar while carrying none of the
/// document's words — that is exactly why scans played back as three words
/// and nothing else. The watermark is instead recognized by the two
/// properties it always has: it REPEATS verbatim on a meaningful share of
/// the document's pages, and it is short.
///
/// The detector is deliberately narrow. It claims "scan" only when it can
/// name the evidence — a repeated watermark token, or pages with no text
/// layer at all. Everything else ("is this page dense enough to be prose?",
/// "does this document mix scanned and typed pages?") is left to the
/// per-page decision at playback time, which has the page in hand. A
/// document-level "no page reaches 200 characters" rule would have been
/// wrong on every dense-but-short fixture and on real running-head pages,
/// and it can never be reviewed by the user who knows what the document
/// contains. When it guesses wrong the user has the force-OCR switch.
public enum PdfScanDetector {

    /// Exact normalized spellings CamScanner's own watermark uses. Compared
    /// against collapsed, lowercased page text, so "Scanned  by CamScanner"
    /// with the PDF's own line breaks still matches.
    public static let watermarkTokens: Set<String> = [
        "scanned by camscanner",
        "scanned with camscanner",
        "generated by camscanner",
        "created by camscanner",
        "camscanner",
    ]

    /// Pages examined per document. The verdict is a document property, and
    /// sampling keeps a 500-page book from paying for 500 `page.string`
    /// reads at import time.
    public static let sampledPages = 12

    /// The share of sampled pages carrying the same string above which that
    /// string is a watermark rather than a running head. The watermark runs
    /// on every page; one repeated page in twelve is just a header.
    public static let repeatedPageFraction = 0.25

    /// Samples pages spread through the document and returns the
    /// document-wide verdict.
    public static func verdict(
        in document: PDFDocument,
        limit: Int = sampledPages
    ) -> PdfScanVerdict {
        let pageCount = document.pageCount
        guard pageCount > 0 else {
            return PdfScanVerdict(looksScanned: false, watermarkOnly: false, sampledPages: 0, reason: "empty document")
        }
        let indices = sampleIndices(pageCount: pageCount, limit: limit)
        var normalized: [String] = []
        var counts: [String: Int] = [:]
        var emptyPages = 0
        for index in indices {
            guard let page = document.page(at: index) else { continue }
            let text = (page.string ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            if text.isEmpty { emptyPages += 1 }
            let squashed = squash(text)
            normalized.append(squashed)
            counts[squashed, default: 0] += 1
        }
        let sampled = normalized.count
        guard sampled > 0 else {
            return PdfScanVerdict(looksScanned: false, watermarkOnly: false, sampledPages: 0,
                                  reason: "no pages could be read")
        }

        // 1) Pages with nothing at all: the blank-scan shape, and the case
        //    PDFKit has always routed to OCR.
        if emptyPages == sampled {
            return PdfScanVerdict(looksScanned: true, watermarkOnly: false, sampledPages: sampled,
                                  reason: "no sampled page has a text layer")
        }

        // 2) The same string on a meaningful share of pages, and it looks
        //    like a scanner watermark: the layer is the watermark, not the
        //    document. This is the CamScanner case — its watermark is a real
        //    text layer, so only repetition plus shortness can identify it.
        if let (dominant, share) = dominant(counts: counts, sampled: sampled),
           share >= repeatedPageFraction,
           looksLikeWatermark(dominant) {
            let percent = Int((share * 100).rounded())
            return PdfScanVerdict(
                looksScanned: true,
                watermarkOnly: true,
                sampledPages: sampled,
                reason: "text layer is the \"\(dominant)\" watermark on \(percent)% of \(sampled) sampled pages"
            )
        }

        // 3) Neither. The sampled pages agree with each other (or differ),
        //    and they carry words — the per-page decision at playback time
        //    handles whatever they are, watermark or prose or thin. The
        //    document-level verdict does not guess at density.
        return PdfScanVerdict(
            looksScanned: false,
            watermarkOnly: false,
            sampledPages: sampled,
            reason: "no repeated scanner watermark on \(sampled) sampled pages"
        )
    }

    /// One page's share of the same test, for callers holding a single page
    /// (the live chapter extraction in the reader, and the mixed document
    /// where only some pages are images).
    public static func pageIsWatermark(_ page: PDFPage) -> Bool {
        let squashed = squash(page.string ?? "")
        return squashed.isEmpty ? false : looksLikeWatermark(squashed)
    }

    /// The pages to examine, spread from first to last so a document with a
    /// text front matter and a scanned body still sees both halves.
    static func sampleIndices(pageCount: Int, limit: Int) -> [Int] {
        guard pageCount > 0 else { return [] }
        let wanted = min(limit, pageCount)
        if wanted <= 1 { return [0] }
        return (0..<wanted).map { step in
            let position = Double(step) / Double(wanted - 1)
            return min(pageCount - 1, Int((position * Double(pageCount - 1)).rounded()))
        }
    }

    /// The most common normalized text layer and its share of the sample.
    /// Ties break toward the longer string: a page whose text is genuinely
    /// there must not lose to an empty page by ordering accident.
    private static func dominant(counts: [String: Int], sampled: Int) -> (String, Double)? {
        var best: (String, Int)?
        for (text, count) in counts {
            if let current = best {
                if count > current.1 || (count == current.1 && text.count > current.0.count) {
                    best = (text, count)
                }
            } else {
                best = (text, count)
            }
        }
        guard let best else { return nil }
        return (best.0, Double(best.1) / Double(sampled))
    }

    /// Collapses whitespace and lowercases, so the same sentence matches
    /// regardless of the line breaks the PDF puts between its words.
    static func squash(_ text: String) -> String {
        text
            .lowercased()
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }

    /// True when a normalized page's whole text layer is a scanner
    /// watermark. The exact spellings first; then the shape — a very short
    /// run that is all it ever says on this page, mentioning scanning or
    /// naming a scanner app.
    ///
    /// Deliberately conservative: an unknown-page "short text" run is NOT
    /// treated as a watermark, because a genuinely short page (a title page,
    /// a chapter stub) would then lose its real words to OCR. What gets
    /// claimed is only what a watermark actually looks like.
    static func looksLikeWatermark(_ squashed: String) -> Bool {
        if watermarkTokens.contains(squashed) { return true }
        let words = squashed.split(separator: " ").map(String.init)
        guard words.count <= 6, !words.isEmpty else { return false }
        // "Scanned by <anything>" covers the localized producer variants.
        if words.count <= 4, words.contains("scanned") || words.contains("generated") || words.contains("created") {
            return true
        }
        // "<App> Scan" / "<App> Scanner" — the producer-name shape.
        let lastWord = words[words.count - 1]
        return words.count <= 5 && (lastWord.hasSuffix("scanner") || lastWord.hasSuffix("scan"))
    }
}
