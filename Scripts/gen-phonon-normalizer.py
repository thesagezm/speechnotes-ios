#!/usr/bin/env python3
r"""Generates PhononNormalizerTable.swift from the Phonon tokenizer.json.

The 191-step Replace/Strip/Prepend normalizer chain of onnx-community/
phonon-31m-en-ONNX is data, not code: this script reads the hub tokenizer
and emits an ICU-ready (pattern, replacement) table the Swift tokenizer
applies in order. Rust-regex \uXXXX / \UXXXXXXXX escapes are rewritten to
ICU \x{...} so NSRegularExpression can compile them; everything else in the
chain (literal classes, \p{...}, lookbehind/lookahead, (?:...) groups)
is ICU-compatible verbatim.

Usage: python3 Scripts/gen-phonon-normalizer.py /path/to/tokenizer.json
(the file lives in /tmp during development; CI does not need it — the
generated table is checked in and only regenerated when the hub re-exports)
"""
import json
import re
import sys


def rust_to_icu(pattern: str) -> str:
    # \U0001faff (Rust 8-digit) and \uXXXX (4-digit) -> \x{XXXX}
    return re.sub(
        r"\\U([0-9a-fA-F]{8})|\\u([0-9a-fA-F]{4})",
        lambda m: "\\x{" + (m.group(1) or m.group(2)).upper() + "}",
        pattern,
    )


def swift_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: gen-phonon-normalizer.py <tokenizer.json>")
    tok = json.load(open(sys.argv[1], encoding="utf-8"))
    steps = tok["normalizer"]["normalizers"]

    out = []
    out.append("// GENERATED by Scripts/gen-phonon-normalizer.py from")
    out.append("// onnx-community/phonon-31m-en-ONNX tokenizer.json (Apache-2.0).")
    out.append("// The hub's Unigram normalizer chain as ordered data: Replace")
    out.append("// steps carry an ICU-translated regex (\\\\uXXXX -> \\\\x{...});")
    out.append("// NSRegularExpression compiles every pattern verbatim. Regenerate")
    out.append("// only if the hub re-exports the tokenizer.")
    out.append("enum PhononNormalizerStep {")
    out.append("    case replace(pattern: String, replacement: String)")
    out.append("    case strip")
    out.append("    case prepend(String)")
    out.append("}")
    out.append("")
    out.append("enum PhononNormalizerTable {")
    out.append("    /// The hub normalizer's steps, in file order. Applied before")
    out.append("    /// the Metaspace pre-tokenizer (see PhononTokenizer).")
    out.append("    static let steps: [PhononNormalizerStep] = [")
    for step in steps:
        kind = step.get("type")
        if kind == "Replace":
            pattern = step["pattern"]
            rx = pattern["Regex"] if "Regex" in pattern else None
            if rx is None:
                literal = pattern["String"]
                # A literal Replace is a plain substring swap — escape it as
                # a regex so one code path handles both.
                icu = re.escape(literal).replace("\\ ", " ")
                out.append(f"        .replace(pattern: {swift_quote(icu)}, replacement: {swift_quote(step['content'])}),")
            else:
                out.append(f"        .replace(pattern: {swift_quote(rust_to_icu(rx))}, replacement: {swift_quote(step['content'])}),")
        elif kind == "Strip":
            out.append("        .strip,")
        elif kind == "Prepend":
            out.append(f"        .prepend({swift_quote(step['prepend'])}),")
        else:
            sys.exit(f"unhandled normalizer step type: {kind}")
    out.append("    ]")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
